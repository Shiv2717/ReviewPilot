"""Filter PR files, parse hunks, and chunk under a token budget."""

from __future__ import annotations

import re
import uuid
from pathlib import PurePosixPath

from app.core.schemas import DiffChunk, DiffFile, DiffHunk

IGNORED_NAMES = frozenset(
    {
        "package-lock.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "Cargo.lock",
        "poetry.lock",
        "Pipfile.lock",
        "composer.lock",
        "Gemfile.lock",
        "go.sum",
    }
)
IGNORED_SUFFIXES = (
    ".min.js",
    ".min.css",
    ".map",
    ".lock",
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".webp",
    ".ico",
    ".pdf",
    ".zip",
    ".gz",
    ".jar",
    ".woff",
    ".woff2",
    ".ttf",
    ".eot",
    ".bin",
    ".exe",
    ".dll",
    ".so",
    ".dylib",
    ".pyc",
)
GENERATED_MARKERS = ("autogenerated", "generated by", "do not edit")
HUNK_RE = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@(.*)$")


def should_ignore_file(filename: str, patch: str | None = None) -> tuple[bool, str | None]:
    name = PurePosixPath(filename).name
    lower = filename.lower()
    if name in IGNORED_NAMES:
        return True, "lockfile"
    if any(lower.endswith(suf) for suf in IGNORED_SUFFIXES):
        return True, "binary_or_minified"
    if "/generated/" in lower or filename.startswith("vendor/"):
        return True, "generated_path"
    if patch:
        head = "\n".join(patch.splitlines()[:5]).lower()
        if any(m in head for m in GENERATED_MARKERS):
            return True, "generated_marker"
    return False, None


def estimate_tokens(text: str) -> int:
    """Rough token estimate (~4 chars/token)."""
    return max(1, len(text) // 4)


def parse_hunks(patch: str) -> list[DiffHunk]:
    """Parse a GitHub unified patch into hunks with old/new line numbers."""
    hunks: list[DiffHunk] = []
    lines = patch.splitlines()
    i = 0
    while i < len(lines):
        match = HUNK_RE.match(lines[i])
        if not match:
            i += 1
            continue
        old_start = int(match.group(1))
        old_count = int(match.group(2) or "1")
        new_start = int(match.group(3))
        new_count = int(match.group(4) or "1")
        header = lines[i]
        i += 1
        body: list[str] = []
        new_nums: list[int | None] = []
        old_nums: list[int | None] = []
        old_line, new_line = old_start, new_start
        while i < len(lines) and not lines[i].startswith("@@"):
            line = lines[i]
            # GitHub may append "\ No newline at end of file"
            if line.startswith("\\"):
                body.append(line)
                new_nums.append(None)
                old_nums.append(None)
                i += 1
                continue
            if line.startswith("+") and not line.startswith("+++"):
                body.append(line)
                new_nums.append(new_line)
                old_nums.append(None)
                new_line += 1
            elif line.startswith("-") and not line.startswith("---"):
                body.append(line)
                new_nums.append(None)
                old_nums.append(old_line)
                old_line += 1
            else:
                # context line (may start with space or be empty after strip in rare cases)
                body.append(line if line.startswith(" ") else f" {line}")
                new_nums.append(new_line)
                old_nums.append(old_line)
                old_line += 1
                new_line += 1
            i += 1
        hunks.append(
            DiffHunk(
                header=header,
                old_start=old_start,
                old_count=old_count,
                new_start=new_start,
                new_count=new_count,
                lines=body,
                new_line_numbers=new_nums,
                old_line_numbers=old_nums,
            )
        )
    return hunks


def annotate_files(files: list[DiffFile]) -> list[DiffFile]:
    """Mark ignored files and attach parsed hunks."""
    annotated: list[DiffFile] = []
    for f in files:
        if f.ignored:
            annotated.append(f.model_copy(update={"hunks": []}))
            continue
        ignored, reason = should_ignore_file(f.filename, f.patch)
        hunks = parse_hunks(f.patch) if f.patch and not ignored else []
        annotated.append(
            f.model_copy(
                update={
                    "ignored": ignored,
                    "ignore_reason": reason,
                    "hunks": hunks,
                }
            )
        )
    return annotated


def chunk_files(files: list[DiffFile], *, token_budget: int) -> list[DiffChunk]:
    """Chunk non-ignored files by file/hunk under an approximate token budget."""
    chunks: list[DiffChunk] = []
    for f in files:
        if f.ignored or not f.hunks:
            continue
        current_hunks: list[DiffHunk] = []
        current_tokens = 0
        for hunk in f.hunks:
            hunk_text = hunk.header + "\n" + "\n".join(hunk.lines)
            tokens = estimate_tokens(hunk_text)
            if current_hunks and current_tokens + tokens > token_budget:
                chunks.append(_make_chunk(f, current_hunks, current_tokens))
                current_hunks = []
                current_tokens = 0
            if tokens > token_budget and not current_hunks:
                # Oversized single hunk: emit alone.
                chunks.append(_make_chunk(f, [hunk], tokens))
                continue
            current_hunks.append(hunk)
            current_tokens += tokens
        if current_hunks:
            chunks.append(_make_chunk(f, current_hunks, current_tokens))
    return chunks


def _make_chunk(file: DiffFile, hunks: list[DiffHunk], tokens: int) -> DiffChunk:
    parts = [f"FILE: {file.filename} ({file.status})"]
    for h in hunks:
        parts.append(h.header)
        parts.extend(h.lines)
    content = "\n".join(parts)
    return DiffChunk(
        chunk_id=str(uuid.uuid4()),
        file_path=file.filename,
        status=file.status,
        hunks=hunks,
        estimated_tokens=tokens,
        content=content,
    )


def process_pull_files(files: list[DiffFile], *, token_budget: int) -> list[DiffChunk]:
    """Full pipeline: annotate then chunk."""
    return chunk_files(annotate_files(files), token_budget=token_budget)
