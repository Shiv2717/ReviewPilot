"""Map findings to diff positions and post a single idempotent GitHub review."""

from __future__ import annotations

from collections import Counter
from typing import Any

from app.core.logging import get_logger
from app.core.schemas import DiffChunk, DiffFile, Finding, Severity
from app.services.github_client import GitHubClient

logger = get_logger(__name__)


class ReviewPublisher:
    """Posts one review per (repo, pr, head_sha); in-memory + DB idempotency."""

    def __init__(self) -> None:
        self._posted: set[tuple[str, str, int, str]] = set()

    def already_posted(self, owner: str, repo: str, number: int, head_sha: str) -> bool:
        return (owner, repo, number, head_sha) in self._posted

    def mark_posted(self, owner: str, repo: str, number: int, head_sha: str) -> None:
        self._posted.add((owner, repo, number, head_sha))

    def map_position(self, finding: Finding, files: list[DiffFile] | list[DiffChunk]) -> int | None:
        """Map a finding to a GitHub review comment `line` on the RIGHT side."""
        for item in files:
            path = item.file_path if isinstance(item, DiffChunk) else item.filename
            hunks = item.hunks
            if path != finding.file_path:
                continue
            for hunk in hunks:
                for num in hunk.new_line_numbers:
                    if num == finding.line_start:
                        return finding.line_start
            # Fallback: clamp to hunk new_start if within range
            for hunk in hunks:
                end = hunk.new_start + max(hunk.new_count, 1) - 1
                if hunk.new_start <= finding.line_start <= end:
                    return finding.line_start
        return None

    def build_summary(self, findings: list[Finding]) -> str:
        counts = Counter(f.severity.value for f in findings)
        rows = " | ".join(
            f"{sev}: {counts.get(sev, 0)}"
            for sev in (
                Severity.CRITICAL.value,
                Severity.HIGH.value,
                Severity.MEDIUM.value,
                Severity.LOW.value,
            )
        )
        lines = [
            "## ReviewPilot Summary",
            "",
            f"| severity counts | {rows} |",
            "",
            f"Posted **{len(findings)}** inline comment(s).",
            "",
            "_Generated by ReviewPilot multi-agent reviewer._",
        ]
        return "\n".join(lines)

    def build_comments(
        self, findings: list[Finding], files: list[DiffFile] | list[DiffChunk]
    ) -> list[dict[str, Any]]:
        comments: list[dict[str, Any]] = []
        for finding in findings:
            line = self.map_position(finding, files)
            if line is None:
                logger.warning(
                    "finding_position_unmapped",
                    file=finding.file_path,
                    line=finding.line_start,
                )
                continue
            body = (
                f"**{finding.title}** ({finding.severity.value}, {finding.agent_name})\n\n"
                f"{finding.explanation}"
            )
            if finding.suggested_fix:
                body += f"\n\n```suggestion\n{finding.suggested_fix}\n```"
            comments.append(
                {
                    "path": finding.file_path,
                    "line": line,
                    "side": "RIGHT",
                    "body": body,
                }
            )
        return comments

    async def publish(
        self,
        client: GitHubClient,
        *,
        owner: str,
        repo: str,
        number: int,
        head_sha: str,
        installation_id: int,
        findings: list[Finding],
        files: list[DiffFile] | list[DiffChunk],
    ) -> dict[str, Any] | None:
        key = (owner, repo, number, head_sha)
        if key in self._posted:
            logger.info("publish_skipped_idempotent", owner=owner, repo=repo, number=number)
            return None
        comments = self.build_comments(findings, files)
        body = self.build_summary(findings)
        result = await client.create_review(
            owner,
            repo,
            number,
            installation_id=installation_id,
            commit_id=head_sha,
            body=body,
            comments=comments,
        )
        self.mark_posted(owner, repo, number, head_sha)
        logger.info(
            "review_published",
            owner=owner,
            repo=repo,
            number=number,
            comments=len(comments),
        )
        return result
